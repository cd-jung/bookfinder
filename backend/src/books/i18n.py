def description(book, lang):
    """The generated description in `lang` (the stored English text is what keyword search uses)."""
    templates = DESCRIPTIONS.get(lang)
    subjects = untokens(book.subjects_text)
    if not templates or len(subjects) < 2:
        return book.description
    words = SUBJECTS[lang]
    return templates[book.genres[0]].format(
        subj=words.get(subjects[0], subjects[0]), subj2=words.get(subjects[1], subjects[1])
    )
