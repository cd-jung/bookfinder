#!/usr/bin/env python3
"""Bundle all *.md scenarios in this folder into scenarios.js.

index.html loads scenarios.js via a <script> tag, so every scenario is
available even when the page is opened directly from disk (file://),
where the browser blocks fetch() of local files.

Usage: python3 build.py
"""

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUTPUT = HERE / "scenarios.js"


def main():
    scenarios = [
        {"name": path.name, "text": path.read_text(encoding="utf-8")}
        for path in sorted(HERE.glob("*.md"))
    ]
    # json.dumps produces a valid JS literal; ensure_ascii avoids encoding issues
    payload = json.dumps(scenarios, ensure_ascii=True, indent=2)
    OUTPUT.write_text(
        "// Generated by build.py - do not edit manually\n"
        f"window.UX_FLOW_SCENARIOS = {payload};\n",
        encoding="utf-8",
    )
    print(f"BUILT:{OUTPUT.name}:{len(scenarios)} scenario(s)")


if __name__ == "__main__":
    main()
